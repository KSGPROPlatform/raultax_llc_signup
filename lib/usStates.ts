// Lookup maps for resolving a code <-> name in either direction (case-insensitive).
const byCode = new Map(US_STATES.map((s) => [s.code.toUpperCase(), s]));
const byName = new Map(US_STATES.map((s) => [s.name.toLowerCase(), s]));

// Resolve a state from either its 2-letter code or full name. Returns undefined
// for anything we don't recognise (free-typed values are still valid elsewhere).
export function resolveState(
  input: string | null | undefined,
): { code: string; name: string } | undefined {
  const v = (input ?? "").trim();
  if (!v) return undefined;
  return byCode.get(v.toUpperCase()) ?? byName.get(v.toLowerCase());
}
